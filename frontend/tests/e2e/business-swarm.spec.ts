import { expect, test } from "@playwright/test";
import { openResultDetail } from "./resultNavigation";

test("uploaded proposal creates a customer swarm with replies, stance history and frozen scenarios", async ({ page }, testInfo) => {
  test.skip(process.env.RUN_BUSINESS_E2E !== "true", "Requires local API/PostgreSQL; no paid inference.");
  test.setTimeout(60_000);
  const api = "/backend/api/v1/business";
  const registration = await page.request.post("/backend/api/auth/register", { data: { name: "Swarm QA", email: `swarm-${Date.now()}@example.com`, password: "synthetic-swarm-test-password" } });
  expect(registration.status()).toBe(201);
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.goto("/business/new");
  await page.getByLabel("Pilih dokumen bisnis").setInputFiles({ name: "swarm-kedai.txt", mimeType: "text/plain", buffer: Buffer.from("Rencana kedai kopi melayani pelanggan pekerja kantor. Supplier memasok bahan; kompetitor dapat mengubah harga.\nHarga jual Rp30.000 per unit.\nBiaya variabel Rp12.000 per unit.\nBiaya tetap Rp36.000.000 per bulan.\nVolume penjualan belum diketahui.") });
  await page.getByLabel("Keterangan dan pertanyaan").fill("Apa yang diperdebatkan customer sebelum mencoba kedai ini dan asumsi apa yang perlu diuji?");
  await page.getByText("Pengaturan tambahan", { exact: true }).click();
  await page.getByRole("combobox", { name: "Klasifikasi data", exact: true }).selectOption("synthetic");
  await page.getByRole("combobox", { name: "Mode analisis", exact: true }).selectOption("fixture");
  await expect(page.getByRole("combobox", { name: "Jenis interaksi", exact: true })).toHaveValue("swarm");
  await expect(page.getByLabel("Jumlah perspektif customer")).toHaveValue("4");
  await page.getByLabel("Wilayah", { exact: true }).fill("DKI Jakarta");
  await page.getByRole("checkbox", { name: /Saya berwenang memakai dokumen ini/ }).check();
  await page.getByLabel("Brief untuk stakeholder").fill("Konsep usaha sintetis untuk menilai manfaat produk dan kemudahan mencoba. Informasi biaya internal tidak dibagikan.");
  await page.getByRole("button", { name: "Mulai analisis", exact: true }).click();
  await expect(page).toHaveURL(/\/business\/analyses\/analysis_/);
  await expect(page.locator(".business-run-header .business-status")).toHaveText(/Selesai/, { timeout: 20000 });
  const id = new URL(page.url()).pathname.split("/").at(-1)!;
  const baseline = await (await page.request.get(`${api}/analyses/${id}`)).json();
  expect(baseline.status).toBe("completed");
  expect(baseline.input_snapshot.personas.filter((p: { role: string }) => p.role === "customer")).toHaveLength(4);
  const customers = new Set(baseline.input_snapshot.personas.filter((p: { role: string }) => p.role === "customer").map((p: { id: string }) => p.id));
  expect(baseline.result.simulation.events.some((e: { kind: string; actor_id: string; target_id: string }) => e.kind === "reply_message" && customers.has(e.actor_id) && customers.has(e.target_id))).toBeTruthy();
  await page.getByRole("button", { name: "Diskusi", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Diskusi stakeholder", exact: true })).toBeVisible();
  await expect(page.getByText("Publik untuk peserta", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: /^Membalas / }).first().click();
  await expect(page.locator(".swarm-message").first()).toBeFocused();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: testInfo.outputPath("swarm-desktop.png") });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.locator(".swarm-discussion").evaluate(element => element.scrollIntoView({ block: "start" }));
  await page.mouse.wheel(0, -72);
  await page.screenshot({ path: testInfo.outputPath("swarm-mobile.png") });
  const pricePersona = baseline.input_snapshot.personas.find((p: { role: string; interests: string[] }) => p.role === "customer" && p.interests.includes("Nilai dan harga"));
  expect(baseline.result.simulation.stances[pricePersona.id].stance_history.length).toBeGreaterThan(0);
  await expect(page.locator(".swarm-positions, .swarm-quality")).toHaveCount(0);
  const exported = await page.request.get(`${api}/analyses/${id}/export`);
  expect(exported.status()).toBe(200);
  expect(await exported.text()).toContain("Posisi dan perubahan sikap sintetis");
  await openResultDetail(page, "scenario");
  await page.getByRole("combobox", { name: "Perubahan kondisi", exact: true }).selectOption("competitor_price_cut");
  await page.getByRole("combobox", { name: /^Asumsi respons bisnis/ }).selectOption("match_price");
  await page.getByRole("button", { name: "Jalankan Chaos Injection" }).click();
  await expect.poll(() => new URL(page.url()).pathname).not.toBe(`/business/analyses/${id}`);
  await expect(page.locator(".business-run-header .business-status")).toHaveText(/Selesai/, { timeout: 20000 });
  const scenarioId = new URL(page.url()).pathname.split("/").at(-1)!;
  const scenario = await (await page.request.get(`${api}/analyses/${scenarioId}`)).json();
  expect(scenario.input_snapshot.personas).toEqual(baseline.input_snapshot.personas);
  expect(scenario.result.simulation.calculation.break_even_units_monthly).toBe("3000");
  const unchanged = await (await page.request.get(`${api}/analyses/${id}`)).json();
  expect(unchanged.result).toEqual(baseline.result);
});
