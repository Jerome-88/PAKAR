import { expect, test } from "@playwright/test";

test("editable synthetic proposal reaches a source-linked fixture report with automatic personas and no model calls", async ({ page }, testInfo) => {
  test.skip(process.env.RUN_BUSINESS_E2E !== "true", "Requires local API/PostgreSQL. Fixture only; no inference.");
  test.setTimeout(60_000);
  const api = "/backend/api/v1/business";
  const registration = await page.request.post("/backend/api/auth/register", { data: { name: "Trial QA", email: `trial-${Date.now()}@example.com`, password: "synthetic-trial-test-password" } });
  expect(registration.status()).toBe(201);
  const paidActions: string[] = [];
  page.on("request", request => {
    if (request.method() === "POST" && /stakeholder-discovery$/.test(new URL(request.url()).pathname)) paidActions.push(request.url());
  });
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.goto("/business/new?example=1");
  await expect(page.getByLabel("Wilayah", { exact: true })).toHaveValue("DKI Jakarta");
  await expect(page.getByLabel("Isi proposal contoh")).toHaveValue(/Harga jual Rp30.000/);
  await page.getByLabel("Pilih contoh bisnis").selectOption("supplier-bandung-v0");
  await expect(page.getByLabel("Wilayah", { exact: true })).toHaveValue("Bandung");
  await expect(page.getByLabel("Isi proposal contoh")).toHaveValue(/Harga jual Rp10.000/);
  await page.getByLabel("Pilih contoh bisnis").selectOption("services-dki-v0");
  await expect(page.getByLabel("Isi proposal contoh")).toHaveValue(/Harga jual Rp150.000/);
  await page.getByLabel("Pilih contoh bisnis").selectOption("coffee-dki-v0");
  const proposal = "Kedai kopi sintetis di DKI Jakarta.\nHarga jual Rp30.000 per unit.\nBiaya variabel Rp15.000 per unit.\nBiaya tetap Rp36.000.000 per bulan.\nVolume penjualan belum diketahui.";
  await page.getByLabel("Isi proposal contoh").fill(proposal);
  const download = page.getByRole("link", { name: "Unduh proposal contoh (.txt)" });
  expect(decodeURIComponent((await download.getAttribute("href"))!.split(",").slice(1).join(","))).toBe(proposal);
  await page.getByText("Pengaturan tambahan", { exact: true }).click();
  await page.getByRole("combobox", { name: "Mode analisis", exact: true }).selectOption("fixture");
  await page.getByText("Pengaturan tambahan", { exact: true }).click();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: testInfo.outputPath("trial-input-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: testInfo.outputPath("trial-input-mobile.png"), fullPage: true });
  await page.getByRole("checkbox", { name: /Saya berwenang memakai dokumen ini/ }).check();
  await page.getByLabel("Brief untuk stakeholder").fill("Konsep usaha sintetis untuk menilai manfaat produk dan kemudahan mencoba. Informasi biaya internal tidak dibagikan.");
  await page.getByRole("button", { name: "Mulai analisis", exact: true }).click();
  await expect(page).toHaveURL(/\/business\/analyses\/analysis_/);
  await expect(page.getByRole("heading", { name: "Executive Summary", exact: true })).toBeVisible({ timeout: 20000 });
  const analysisId = new URL(page.url()).pathname.split("/").at(-1)!;
  const analysis = await (await page.request.get(`${api}/analyses/${analysisId}`)).json();
  expect(analysis.input_snapshot.personas.length).toBeGreaterThanOrEqual(2);
  expect(analysis.input_snapshot.personas.every((p: { reviewed: boolean }) => !p.reviewed)).toBeTruthy();
  expect(analysis.input_snapshot.input_mode).toBe("automatic-v1");
  const project = await (await page.request.get(`${api}/projects/${analysis.project_id}`)).json();
  expect(project.documents[0].name).toBe("contoh-coffee-dki-v0.txt");
  expect(project.claims.find((c: { variable: string }) => c.variable === "variable_cost").value).toBe("15000");
  expect(project.claims.every((c: { review_status: string }) => c.review_status === "pending")).toBeTruthy();
  const report = await (await page.request.get(`${api}/analyses/${analysisId}/report`)).json();
  expect(report.sections).toHaveLength(8);
  expect(report.appendix.calculation.break_even_units_monthly).toBe("2400");
  expect(report.appendix.calculation.profit_monthly).toBeNull();
  expect(report.appendix.provenance.execution_kind).toBe("fixture");
  expect(report.findings.every((f: { status: string }) => f.status === "NEEDS_VALIDATION")).toBeTruthy();
  expect(paidActions).toEqual([]);
  await page.screenshot({ path: testInfo.outputPath("trial-output-mobile.png"), fullPage: true });
});

test("upload and a description start an analysis with automatically generated personas", async ({ page }) => {
  test.skip(process.env.RUN_BUSINESS_E2E !== "true", "Requires local API/PostgreSQL; fixture only.");
  test.setTimeout(45_000);
  const registration = await page.request.post("/backend/api/auth/register", { data: { name: "Upload QA", email: `upload-${Date.now()}@example.com`, password: "synthetic-upload-test-password" } });
  expect(registration.status()).toBe(201);
  await page.goto("/business/new");
  await page.getByLabel("Pilih dokumen bisnis").setInputFiles({ name: "proposal-roti.txt", mimeType: "text/plain", buffer: Buffer.from("Produsen roti memasok customer toko kelontong. Supplier menyediakan tepung.\nHarga jual Rp10.000 per unit.\nBiaya variabel Rp6.000 per unit.\nBiaya tetap Rp12.000.000 per bulan.\nVolume penjualan belum diketahui.") });
  await expect(page.getByLabel("Nama analisis", { exact: true })).toHaveValue("proposal-roti");
  await page.getByLabel("Keterangan dan pertanyaan").fill("Apa risiko ketergantungan pemasok tepung dan berapa BEP usaha roti ini?");
  await page.getByText("Pengaturan tambahan", { exact: true }).click();
  await page.getByRole("combobox", { name: "Klasifikasi data", exact: true }).selectOption("synthetic");
  await page.getByRole("combobox", { name: "Mode analisis", exact: true }).selectOption("fixture");
  await page.getByRole("checkbox", { name: /Saya berwenang memakai dokumen ini/ }).check();
  await page.getByLabel("Brief untuk stakeholder").fill("Konsep usaha sintetis untuk menilai manfaat produk dan kemudahan mencoba. Informasi biaya internal tidak dibagikan.");
  await page.getByRole("button", { name: "Mulai analisis", exact: true }).click();
  await expect(page).toHaveURL(/\/business\/analyses\/analysis_/);
  await expect(page.getByRole("heading", { name: "Executive Summary", exact: true })).toBeVisible({ timeout: 20000 });
  const id = new URL(page.url()).pathname.split("/").at(-1)!;
  const response = await page.request.get(`/backend/api/v1/business/analyses/${id}`);
  const analysis = await response.json();
  expect(analysis.status).toBe("completed");
  expect(analysis.input_snapshot.personas.map((p: { role: string }) => p.role)).toContain("supplier");
  expect(analysis.input_snapshot.context.industry).toBe("Belum ditentukan");
  expect(analysis.result.simulation.calculation.break_even_units_monthly).toBe("3000");
  expect(analysis.result.simulation.calculation.profit_monthly).toBeNull();
});
