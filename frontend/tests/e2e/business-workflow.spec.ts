import { expect, test } from "@playwright/test";
import { openResultDetail } from "./resultNavigation";

test("PAKAR synthetic proposal → automatic personas → interaction trace → versioned chaos", async ({ page }, testInfo) => {
  test.skip(process.env.RUN_BUSINESS_E2E !== "true", "Requires FastAPI, PostgreSQL and an embedded worker.");
  test.setTimeout(90_000);
  const registered = await page.request.post("/backend/api/auth/register", { data: { name: "PAKAR Analyst", email: `pakar-${Date.now()}-${testInfo.workerIndex}@example.com`, password: "pakar-test-password" } });
  expect(registered.status()).toBe(201);
  await page.goto("/business/new?example=1");
  await expect(page.getByRole("heading", { name: "Analisis bisnis baru" })).toBeVisible();
  await page.getByText("Pengaturan tambahan", { exact: true }).click();
  await page.getByRole("combobox", { name: "Mode analisis", exact: true }).selectOption("fixture");
  await page.getByRole("checkbox", { name: /Saya berwenang memakai dokumen ini/ }).check();
  await page.getByLabel("Brief untuk stakeholder").fill("Konsep usaha sintetis untuk menilai manfaat produk dan kemudahan mencoba. Informasi biaya internal tidak dibagikan.");
  await page.getByRole("button", { name: "Mulai analisis", exact: true }).click();
  await expect(page).toHaveURL(/\/business\/analyses\/analysis_/);
  await expect(page.locator(".business-run-header .business-status")).toHaveText(/Selesai/, { timeout: 20000 });
  const baselineId = page.url().split("/").at(-1)!;
  const baseline = await (await page.request.get(`/backend/api/v1/business/analyses/${baselineId}`)).json();
  await openResultDetail(page, "findings");
  expect(baseline.result.simulation.calculation.break_even_units_monthly).toBe("2000");
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.screenshot({ path: testInfo.outputPath("pakar-findings-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole("heading", { name: "Keputusan yang perlu divalidasi." })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: testInfo.outputPath("pakar-findings-mobile.png"), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1100 });
  await openResultDetail(page, "timeline");
  await expect(page.locator(".business-timeline > li")).not.toHaveCount(0);
  await page.getByRole("heading", { name: "Peta interaksi stakeholder" }).scrollIntoViewIfNeeded();
  await page.getByRole("combobox", { name: "Stakeholder yang diperiksa" }).selectOption(baseline.input_snapshot.personas.find((p: { role: string }) => p.role === "supplier").id);
  await page.locator(".business-graph").getByText("Provenance profil stakeholder", { exact: true }).click();
  await page.locator(".business-graph summary").filter({ hasText: /Periksa \d+ event penyebab/ }).first().click();
  await page.locator(".business-graph").screenshot({ path: testInfo.outputPath("pakar-graph-desktop.png") });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole("combobox", { name: "Stakeholder yang diperiksa" })).toBeVisible();
  await page.locator(".business-graph").screenshot({ path: testInfo.outputPath("pakar-graph-mobile.png") });
  await page.setViewportSize({ width: 1440, height: 1100 });
  await openResultDetail(page, "scenario");
  await page.getByRole("combobox", { name: "Perubahan kondisi", exact: true }).selectOption("competitor_price_cut");
  await page.getByRole("combobox", { name: /^Asumsi respons bisnis/ }).selectOption("match_price");
  await page.getByRole("button", { name: "Jalankan Chaos Injection" }).click();
  await expect.poll(() => new URL(page.url()).pathname).not.toBe(`/business/analyses/${baselineId}`);
  await expect(page.locator(".business-run-header .business-status")).toHaveText(/Selesai/, { timeout: 20000 });
  await openResultDetail(page, "scenario");
  await expect(page.getByRole("cell", { name: "3.000", exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("pakar-comparison-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: testInfo.outputPath("pakar-comparison-mobile.png"), fullPage: true });
  const unchanged = await (await page.request.get(`/backend/api/v1/business/analyses/${baselineId}`)).json();
  expect(unchanged.result).toEqual(baseline.result);
});
