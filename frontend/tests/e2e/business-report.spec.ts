import { expect, test } from "@playwright/test";

test("lean results preserve avatar identity, archived export and immutable scenario output", async ({ page }, testInfo) => {
  test.skip(process.env.RUN_BUSINESS_E2E !== "true", "Requires local API/PostgreSQL; fixture engine only.");
  test.setTimeout(90_000);
  const api = "/backend/api/v1/business";
  const avatarRequests: string[] = [];
  page.on("request", request => { if (/(^|\.)(dicebear\.com|draftbit\.com|figma\.com)$/i.test(new URL(request.url()).hostname)) avatarRequests.push(request.url()); });
  expect((await page.request.post("/backend/api/auth/register", { data: { name: "Report QA", email: `report-${Date.now()}@example.com`, password: "report-fixture-test-password" } })).status()).toBe(201);
  let project = await (await page.request.post(`${api}/projects`, { data: { name: "Ekspansi kedai - contoh hasil", industry: "F&B", region: "DKI Jakarta", target_customer: "Pekerja kantor", decision_question: "Apa yang perlu diperbaiki sebelum membuka kedai?", data_classification: "synthetic" } })).json();
  const path = `${api}/projects/${project.id}`;
  project = await (await page.request.post(`${path}/documents`, { multipart: { files: { name: "proposal.txt", mimeType: "text/plain", buffer: Buffer.from("Harga jual Rp30.000 per unit.\nBiaya variabel Rp12.000 per unit.\nBiaya tetap Rp36.000.000 per bulan.\nVolume belum diuji.\n") } } })).json();
  project = await (await page.request.post(`${path}/claims/approve`, { data: { expected_revision: project.revision } })).json();
  for (const [role, name] of [["operator", "Operator contoh"], ["supplier", "Pemasok contoh"], ["customer", "Customer contoh"], ["competitor", "Competitor contoh"]]) {
    expect((await page.request.post(`${path}/personas?expected_revision=${project.revision}`, { data: { id: "placeholder", name, role, goals: ["Uji konsep dengan perspektif sintetis"], constraints: ["Tidak mengarang demand"], reviewed: true } })).status()).toBe(201);
    project = await (await page.request.get(path)).json();
  }
  const waitRun = async (id: string) => expect.poll(async () => (await (await page.request.get(`${api}/analyses/${id}`)).json()).status, { timeout: 20000 }).toMatch(/completed|partial/);
  await page.goto(`/business/projects/${project.id}?tab=personas`);
  const original = page.locator(".business-persona").filter({ has: page.getByRole("heading", { name: "Operator contoh", exact: true }) });
  const source = await original.locator("img.persona-avatar").getAttribute("src");
  expect(source).toMatch(/^data:image\/svg\+xml/);
  const queued = await page.request.post(`${path}/analyses`, { data: { expected_revision: project.revision, engine: "fixture", rounds: 2, max_personas: 4 } });
  expect(queued.status()).toBe(202);
  const baseline = await queued.json();
  await waitRun(baseline.id);
  const frozen = await (await page.request.get(`${api}/analyses/${baseline.id}`)).json();
  expect(frozen.result.simulation.calculation.break_even_units_monthly).toBe("2000");
  const operator = frozen.input_snapshot.personas.find((p: { role: string }) => p.role === "operator");
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`/business/analyses/${baseline.id}`);
  await expect(page.getByRole("button", { name: "Laporan lengkap", exact: true })).toHaveCount(0);
  await expect(page.getByRole("heading", { name: "Assumption Register", exact: true })).toHaveCount(0);
  const node = page.locator(".result-graph-node").filter({ has: page.locator("title", { hasText: operator.name }) });
  await expect(node.locator("image")).toHaveAttribute("href", source!);
  await node.focus();
  await node.press("Space");
  await expect(node).toHaveAttribute("aria-pressed", "true");
  await expect(page.locator(".result-graph-detail img")).toHaveAttribute("src", source!);
  await page.locator(".result-graph").screenshot({ path: testInfo.outputPath("results-graph-desktop.png") });
  const report = await (await page.request.get(`${api}/analyses/${baseline.id}/report`)).json();
  expect(report.sections).toHaveLength(8);
  const exported = await page.request.get(`${api}/analyses/${baseline.id}/export`);
  expect(exported.status()).toBe(200);
  expect(await exported.text()).not.toContain("<pre>");
  const scenarioResponse = await page.request.post(`${api}/analyses/${baseline.id}/scenarios`, { data: { shock: { kind: "competitor_price_cut", magnitude_percent: 20, effective_round: 2, duration_rounds: 2, region: "DKI Jakarta", response_strategy: "match_price", description: "Contoh untuk memeriksa hasil tersimpan" } } });
  expect(scenarioResponse.status()).toBe(202);
  const scenario = await scenarioResponse.json();
  await waitRun(scenario.id);
  const scenarioReport = await (await page.request.get(`${api}/analyses/${scenario.id}/report`)).json();
  expect(scenarioReport.scenario.metrics.find((m: { metric: string }) => m.metric === "break_even_units_monthly").after).toBe("3000");
  const archive = await page.context().newPage();
  await archive.setContent(await (await page.request.get(`${api}/analyses/${scenario.id}/export`)).text());
  await archive.setViewportSize({ width: 390, height: 844 });
  await archive.locator("#scenario-impact").screenshot({ path: testInfo.outputPath("archive-scenario-mobile.png") });
  await expect(archive.getByText(/Geser tabel untuk melihat kolom Delta/)).toBeVisible();
  await archive.close();
  const dense = structuredClone(frozen);
  dense.input_snapshot.personas = Array.from({ length: 120 }, (_, n) => n < frozen.input_snapshot.personas.length ? frozen.input_snapshot.personas[n] : { ...operator, id: `dense-${n}`, name: `Stakeholder ${n}`, role: "customer", relationships: [] });
  await page.route(`**${api}/analyses/${baseline.id}`, route => route.fulfill({ json: dense }));
  await page.goto(`/business/analyses/${baseline.id}`);
  await expect(page.locator(".result-graph-node image")).toHaveCount(120);
  await page.getByLabel("Lihat persona").selectOption("dense-60");
  await expect(page.getByLabel("Alasan persona terpilih")).toContainText("Stakeholder 60");
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator(".result-graph-stage")).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  expect(avatarRequests).toEqual([]);
  const unchanged = await (await page.request.get(`${api}/analyses/${baseline.id}`)).json();
  expect(unchanged.result).toEqual(frozen.result);
});
